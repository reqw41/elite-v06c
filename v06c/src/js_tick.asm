; js_tick (обычный образ): крен и тангаж по клавишам — в обработчике кадра, 50 раз в секунду, а не раз за проход
; (как у Elite Legend на ZX: поворот откликается сразу, как бы медленно ни рисовался кадр). Тот же кусок DOKEY BBC
; (js_upd: шаг крена 7, тангажа 14) и возврат к середине (cntr: крен 2 — при отпущенных клавишах крена, тангаж 1),
; только каждый кадр; M% по-прежнему возвращает к середине и раз за проход. Автопилот стыковки ведёт ручки раз за проход (DOKEY, dk_auto). Зовётся
; обработчиком кадра после пересчёта клавиш, пока главный цикл в DOKEY, а не на паузе (fly_on).
js_tick:
	ld	a, (auto)
	or	a
	ret	nz
	ld	a, (T)			; T — рабочая ячейка прерванной программы, BUMP2 и REDU2 её портят
	push	af
	ld	a, (v_frames)		; клавиатура опрашивается через кадр (kb_rows пересчитан до js_tick): клавиши перечитать
	rrca				; в кадре опроса (v_frames уже нечётный), в прочих — KL+3..KL+6 те же (их держит и DOKEY)
	jp	nc, jt_u
	ld	hl, 0			; KL+3..KL+6 — нажаты ли клавиши крена и тангажа сейчас
	ld	(KL + 3), hl
	ld	(KL + 5), hl
	ld	c, 6
jt_l:
	call	DKS1
	dec	c
	ld	a, c
	cp	2
	jp	nz, jt_l
	call	jt_kick			; крен из середины — сразу заметный (как у ZX)
jt_u:
	call	js_upd
	ld	hl, (KL + 3)		; крен к середине — только когда клавиши крена отпущены (как у ZX 48K: до упора
	ld	a, l			; за 0,36 с, а не за 0,58)
	or	h
	jp	nz, jt_y
	ld	hl, JSTX
	ld	b, (hl)
	call	cntr
	call	cntr
	ld	(hl), b
jt_y:
	ld	hl, JSTY
	ld	b, (hl)
	call	cntr
	ld	(hl), b
	pop	af
	ld	(T), a
	ret
jt_end:
