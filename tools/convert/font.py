def table():
    font = bytearray(768)
    rows = [l.split() for l in FONT.strip().splitlines()]
    assert len(rows) == 96
    for i, r in enumerate(rows):
        assert int(r[0], 16) == 32 + i and len(r) == 9, r
        font[i * 8:i * 8 + 8] = bytes(int(x, 16) for x in r[1:])
    return bytes(font)


