def table_ru(font):
    f = bytearray(font)
    for i, ch in enumerate(KOI7):
        if ch in SAME:
            g = font[(ord(SAME[ch]) - 32) * 8:(ord(SAME[ch]) - 32) * 8 + 8]
        else:
            rows = CYR[ch] + [''] * (8 - len(CYR[ch]))
            g = bytes(sum(0x40 >> k for k, c in enumerate(r) if c == '#') for r in rows)
        f[(96 + i - 32) * 8:(96 + i - 32) * 8 + 8] = g
    return bytes(f)


def chunk(tag, data):
    return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xFFFFFFFF)


def png(font, path, scale=4):
    """Лист 16×6 знаков, клетка 10×10 точек."""
    w, h = 16 * 10 * scale, 6 * 10 * scale
    px = [[0] * (16 * 10) for _ in range(6 * 10)]
    for i in range(96):
        for y in range(8):
            for x in range(8):
                if font[i * 8 + y] & (0x80 >> x):
                    px[(i // 16) * 10 + 1 + y][(i % 16) * 10 + 1 + x] = 255
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        raw += bytes(px[y // scale][x // scale] for x in range(w))
    open(path, 'wb').write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 0, 0, 0, 0)) +
                           chunk(b'IDAT', zlib.compress(bytes(raw))) + chunk(b'IEND', b''))


