def chars(s, lat):
    """Знаки текста → коды; lat — включена ли латиница на входе. Возвращает (коды, lat)."""
    out = []
    for ch in s:
        if ch == '_':
            lat = not lat
            out.append(95)
        elif ch == 'Ё':
            out.append(64 + KOI7.index('Е'))
        elif ch in KOI7 and not lat:
            out.append(64 + KOI7.index(ch))
        else:
            c = ord(ch)
            assert 32 <= c < 64 or (lat and 65 <= c <= 90), (s, ch)
            out.append(c)
    return out, lat


def parse(s):
    """Текст → куски: ('c', код), ('w', имя), ('g', имя)."""
    out, lat = [], False
    for m in re.finditer(r'\{(\d+)\}|<(\w+)>|\[(\w+)\]|[^{<\[]+', s):
        if m.group(1):
            out.append(('c', int(m.group(1))))
        elif m.group(2):
            out.append(('w', m.group(2)))
        elif m.group(3):
            out.append(('g', m.group(3)))
        else:
            cs, lat = chars(m.group(0), lat)
            out += [('c', c) for c in cs]
    assert not lat, s
    return out


def autowords(pairs, room):
    """Сжатие: до room самых выгодных повторяющихся кусков текста (кириллица, пробел, знаки) — отдельными словами.
    Куски ищутся жадно: выгода = повторов · (длина − 1) − (длина + 1), длина — в байтах после замены пар."""
    pairset = set(pairs)
    allt = lambda: [WORDS[w] for w in WORDS] + [x for g in GROUPS.values() for x in g] + [
        BRIEF1, BRIEF2, DEBRIEF1, INCOMING, BRIEF3, DEBRIEF2] + CAPT + M28 + RUS + [t for _, t in MZ]

    def blen(sub):
        cs, _ = chars(sub, False)
        n, i = 0, 0
        while i < len(cs):
            i += 2 if i + 1 < len(cs) and (cs[i], cs[i + 1]) in pairset else 1
            n += 1
        return n
    ok = re.compile(r"^[А-Я ,.\-!?:]+$")
    for k in range(room):
        cnt = {}
        for t in allt():
            for part in re.split(r'\{\d+\}|<\w+>|\[\w+\]|_[^_]*_', t):
                for L in range(3, 16):
                    for i in range(len(part) - L + 1):
                        sub = part[i:i + L]
                        if ok.match(sub):
                            cnt[sub] = cnt.get(sub, 0) + 1
        best, gain = None, 0
        for sub, c in cnt.items():
            if c < 2:
                continue
            n = blen(sub)
            g = c * (n - 1) - (n + 1)
            if g > gain:
                best, gain = sub, g
        if not best:
            break
        name = 'a%d' % k
        WORDS[name] = best
        rep = lambda t: re.sub(r'(_[^_]*_|\{\d+\}|<\w+>|\[\w+\])|' + re.escape(best),
                               lambda m: m.group(1) or '<%s>' % name, t)
        for w in list(WORDS):
            if w != name:
                WORDS[w] = rep(WORDS[w])
        for g in GROUPS:
            GROUPS[g] = [rep(x) for x in GROUPS[g]]
        for i, t in enumerate(CAPT):
            CAPT[i] = rep(t)
        for i, t in enumerate(M28):
            M28[i] = rep(t)
        for i, t in enumerate(RUS):
            RUS[i] = rep(t)
        for i, (n, t) in enumerate(MZ):
            MZ[i] = (n, rep(t))
        g_ = globals()
        for v in ('BRIEF1', 'BRIEF2', 'DEBRIEF1', 'INCOMING', 'BRIEF3', 'DEBRIEF2'):
            g_[v] = rep(g_[v])


