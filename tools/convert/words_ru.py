def parse(s):
    """Текст слова → список кусков: ('c', код) — знак или буква, ('r', n) — слово, ('k', n) — управляющий код."""
    out, lat = [], False
    for m in re.finditer(r'\{(\d+)\}|<(\d+)>|.', s):
        if m.group(1):
            out.append(('r', int(m.group(1))))
        elif m.group(2):
            out.append(('k', int(m.group(2))))
        else:
            ch = m.group(0)
            if ch == '_':
                lat = not lat
                out.append(('c', 95))
            elif ch == 'Ё':
                out.append(('c', 64 + KOI7.index('Е')))
            elif ch in KOI7:
                assert not lat, s
                out.append(('c', 64 + KOI7.index(ch)))
            else:
                c = ord(ch)
                assert 32 <= c < 64 or (lat and 65 <= c <= 90), (s, ch)
                out.append(('c', c))
    assert not lat, s
    return out


def is_letter(p):
    return p[0] == 'c' and 64 <= p[1] <= 94


def pairs(toks, n=32):
    """Жадно n пар русских букв: каждый раз — самая частая пара, она заменяется во всех словах."""
    table = []
    for _ in range(n):
        cnt = collections.Counter()
        for t in toks:
            for a, b in zip(t, t[1:]):
                if is_letter(a) and is_letter(b):
                    cnt[(a[1], b[1])] += 1
        (a, b), _ = cnt.most_common(1)[0]
        k = len(table)
        table.append((a, b))
        for i, t in enumerate(toks):
            out, j = [], 0
            while j < len(t):
                if j + 1 < len(t) and t[j] == ('c', a) and t[j + 1] == ('c', b):
                    out.append(('p', k))
                    j += 2
                else:
                    out.append(t[j])
                    j += 1
            toks[i] = out
    return table


def code(p):
    kind, v = p
    if kind == 'c' or kind == 'k':
        return v
    if kind == 'p':
        return 128 + v
    if v < 96:
        return 160 + v
    if v < 128:
        return v
    assert 128 <= v <= 145, v
    return v - 114


def build():
    """Слова QQ18 (куски после замены пар) и таблица пар: [(код буквы, код буквы), …]."""
    toks = [parse(RU[i]) for i in range(150)]
    return toks, pairs(toks)


def main():
    toks, table = build()
    out = ['; создано tools/convert/words_ru.py, руками не править', 'QQ18:']
    size = 0
    for i, t in enumerate(toks):
        b = [code(p) ^ RE for p in t] + [0]
        size += len(b)
        out.append('\tdb ' + ', '.join('0x%02X' % x for x in b) + ' ; %d: %s' % (i, RU[i]))
    out.append('; пары русских букв для слов (коды 128–159); у названий систем — QQ16, как у BBC')
    out.append('QQ16R:')
    out.append('\tdb ' + ', '.join('%d' % x for ab in table for x in ab))
    out.append('; ' + ' '.join(KOI7[a - 64] + KOI7[b - 64] for a, b in table))
    open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('v06c/data/words_ru.asm: словарь %d Б + пары %d Б' % (size, 2 * len(table)))


if __name__ == '__main__':
    main()
